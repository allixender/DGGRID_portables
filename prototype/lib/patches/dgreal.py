#!/usr/bin/env python3
"""dgreal.py <DGGRID/src dir>

Rewrites DGGRID's `long double` into a `dgreal` typedef, in place (prototype source
copy only, see ../setup_src.sh). Generated instead of a static patch because it touches
~1000 lines in ~130 files and would conflict with almost every upstream bump.

  long double          -> dgreal
  sinl(x), acosl(x)..  -> std::sin(x), std::acos(x).. (overloaded on the argument type;
                          sinl() on a double would still compute in long double)
  1.5L, 1e-9L          -> DGR(1.5), DGR(1e-9)  (an L literal promotes the whole expression)
  "%LF", "LF" in       -> "%" DG_RFMT_L "F"     ("l" for double: printf ignores it,
  format strings                                   scanf needs it for double*)

dglib/DgReal.h picks the type: `-DDG_REAL_DOUBLE` -> double, otherwise long double, which
must reproduce upstream byte for byte. Idempotent. Prints what it changed.
"""
import os
import re
import sys

HEADER = """#ifndef DGREAL_H
#define DGREAL_H
// generated by prototype/lib/patches/dgreal.py: floating point type of dglib
#include <cmath>
#ifdef DG_REAL_DOUBLE
typedef double dgreal;
#define DGR(x) x
#define DG_RFMT_L "l"
#else
typedef long double dgreal;
#define DGR(x) x ## L
#define DG_RFMT_L "L"
#endif
#endif
"""
INCLUDE = "#include <dglib/DgReal.h> // dgreal.py\n"

LONG_DOUBLE = re.compile(r"\blong\s+double\b")
# not after `::` (std::tr1::lrintl in a dead #if branch of DgUtil.h stays as it is)
MATHL = re.compile(r"(?<![\w:])(sin|cos|tan|asin|acos|atan|atan2|sqrt|fabs|pow|exp|log|floor|ceil|fmod|llrint|lrint|lround|llround)l\s*\(")
LITERAL = re.compile(r"(?<![\w.])((?:\d+\.\d*|\.\d+)(?:[eE][-+]?\d+)?|\d+[eE][-+]?\d+)[lL]\b")
STRING = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
FMT_IN = re.compile(r"(%[-+ #0-9.*]*)L([fFgGeEaA])")
FMT_LEAD = re.compile(r"^L([fFgGeE])(?![A-Za-z])")  # "LF" appended to a dynamically built "%#.<n>"


def fix_string(m, log):
    body = m.group(1)
    new = FMT_IN.sub(lambda f: f'{f.group(1)}" DG_RFMT_L "{f.group(2)}', body)
    new = FMT_LEAD.sub(lambda f: f'" DG_RFMT_L "{f.group(1)}', new)
    if new == body:
        return m.group(0)
    out = f'"{new}"'.replace('"" ', "").replace(' ""', "")
    log.append(f"{m.group(0)} -> {out}")
    return out


def rewrite(text, log):
    counts = {}
    text, counts["long double"] = LONG_DOUBLE.subn("dgreal", text)
    text, counts["*l() calls"] = MATHL.subn(lambda m: f"std::{m.group(1)}(", text)
    text, counts["L literals"] = LITERAL.subn(lambda m: f"DGR({m.group(1)})", text)
    before = len(log)
    text = STRING.sub(lambda m: fix_string(m, log), text)
    counts["format strings"] = len(log) - before
    return text, counts


def main():
    src = sys.argv[1]
    hdr = os.path.join(src, "lib/dglib/include/dglib/DgReal.h")
    with open(hdr, "w") as f:
        f.write(HEADER)

    total = {}
    files = 0
    fmt_log = []
    for dirpath, _, names in os.walk(src):
        for name in sorted(names):
            if not name.endswith((".h", ".hpp", ".cpp")) or name == "DgReal.h":
                continue
            path = os.path.join(dirpath, name)
            with open(path, encoding="latin-1", newline="") as f:
                old = f.read()
            log = []
            new, counts = rewrite(old, log)
            if new == old:
                continue
            if INCLUDE not in new:
                new = INCLUDE + new
            with open(path, "w", encoding="latin-1", newline="") as f:
                f.write(new)
            files += 1
            for k, v in counts.items():
                total[k] = total.get(k, 0) + v
            fmt_log += [f"  {os.path.relpath(path, src)}: {l}" for l in log]

    print(f"dgreal.py: {files} files rewritten, " + ", ".join(f"{v} {k}" for k, v in total.items()))
    for line in fmt_log:
        print(line)


if __name__ == "__main__":
    main()
